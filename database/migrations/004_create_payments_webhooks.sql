CREATE TABLE IF NOT EXISTS payments (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  reservation_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(32) NOT NULL,
  external_id VARCHAR(160) NULL,
  idempotency_key VARCHAR(120) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  method VARCHAR(16) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'BRL',
  provider_status VARCHAR(48) NULL,
  description VARCHAR(255) NOT NULL,
  payer_email VARCHAR(254) NOT NULL,
  checkout_url VARCHAR(1000) NULL,
  pix_qr_code TEXT NULL,
  pix_copy_paste TEXT NULL,
  paid_at DATETIME NULL,
  refunded_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY payments_provider_external_uq (provider, external_id),
  UNIQUE KEY payments_idempotency_uq (provider, idempotency_key),
  KEY payments_reservation_idx (reservation_id),
  KEY payments_status_idx (status),
  CONSTRAINT payments_reservation_fk FOREIGN KEY (reservation_id) REFERENCES reservations (id),
  CONSTRAINT payments_status_chk CHECK (status IN ('pending', 'processing', 'paid', 'failed', 'cancelled', 'refunded', 'partially_refunded')),
  CONSTRAINT payments_method_chk CHECK (method IN ('pix', 'card')),
  CONSTRAINT payments_amount_chk CHECK (amount > 0),
  CONSTRAINT payments_currency_chk CHECK (currency = 'BRL')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  payment_id BIGINT UNSIGNED NULL,
  provider VARCHAR(32) NOT NULL,
  external_event_id VARCHAR(160) NOT NULL,
  event_type VARCHAR(80) NOT NULL,
  action VARCHAR(120) NULL,
  provider_status VARCHAR(48) NULL,
  payload JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY payment_events_payment_idx (payment_id),
  KEY payment_events_provider_event_idx (provider, external_event_id),
  CONSTRAINT payment_events_payment_fk FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS refunds (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  payment_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(32) NOT NULL,
  external_id VARCHAR(160) NULL,
  idempotency_key VARCHAR(120) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  reason VARCHAR(255) NULL,
  requested_by_email VARCHAR(254) NULL,
  processed_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY refunds_provider_external_uq (provider, external_id),
  UNIQUE KEY refunds_provider_idempotency_uq (provider, idempotency_key),
  KEY refunds_payment_idx (payment_id),
  CONSTRAINT refunds_payment_fk FOREIGN KEY (payment_id) REFERENCES payments (id),
  CONSTRAINT refunds_status_chk CHECK (status IN ('pending', 'processed', 'failed', 'cancelled')),
  CONSTRAINT refunds_amount_chk CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS webhook_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  provider VARCHAR(32) NOT NULL,
  external_event_id VARCHAR(160) NOT NULL,
  request_id VARCHAR(160) NULL,
  event_type VARCHAR(80) NOT NULL,
  action VARCHAR(120) NULL,
  signature VARCHAR(512) NULL,
  payload JSON NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'received',
  attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  processed_at DATETIME NULL,
  last_error VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY webhook_events_provider_event_uq (provider, external_event_id),
  KEY webhook_events_status_idx (status),
  CONSTRAINT webhook_events_status_chk CHECK (status IN ('received', 'processing', 'processed', 'ignored', 'failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
