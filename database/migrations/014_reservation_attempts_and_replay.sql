CREATE TABLE IF NOT EXISTS reservation_attempts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  flow_id_hash CHAR(64) NOT NULL,
  attempt_id VARCHAR(80) NOT NULL,
  attempt_id_hash CHAR(64) NOT NULL,
  owner_user_id VARCHAR(36) NOT NULL,
  owner_customer_id BIGINT UNSIGNED NOT NULL,
  owner_session_token_hash CHAR(64) NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 0,
  state VARCHAR(24) NOT NULL DEFAULT 'active',
  reservation_date DATE NULL,
  start_time TIME NULL,
  end_time TIME NULL,
  guest_count SMALLINT UNSIGNED NULL,
  duration_minutes SMALLINT UNSIGNED NULL,
  selected_table_ids JSON NULL,
  hold_expires_at DATETIME NULL,
  reservation_id BIGINT UNSIGNED NULL,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY reservation_attempts_flow_uq (flow_id_hash),
  UNIQUE KEY reservation_attempts_attempt_id_uq (attempt_id),
  UNIQUE KEY reservation_attempts_attempt_uq (attempt_id_hash),
  KEY reservation_attempts_owner_idx (owner_user_id, owner_customer_id),
  KEY reservation_attempts_expiry_idx (state, expires_at),
  CONSTRAINT reservation_attempts_state_chk CHECK (state IN ('active', 'confirmed', 'expired', 'invalidated'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS reservation_operations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  attempt_id_hash CHAR(64) NOT NULL,
  operation_key VARCHAR(160) NOT NULL,
  content_fingerprint CHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  reservation_id BIGINT UNSIGNED NULL,
  result_public_code VARCHAR(80) NULL,
  replay_ciphertext BLOB NULL,
  replay_nonce VARBINARY(24) NULL,
  replay_auth_tag VARBINARY(32) NULL,
  replay_key_version VARCHAR(40) NULL,
  replay_expires_at DATETIME NULL,
  notification_dedupe_key VARCHAR(160) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY reservation_operations_attempt_operation_uq (attempt_id_hash, operation_key),
  KEY reservation_operations_reservation_idx (reservation_id),
  KEY reservation_operations_replay_expiry_idx (replay_expires_at),
  UNIQUE KEY reservation_operations_notification_uq (notification_dedupe_key),
  CONSTRAINT reservation_operations_status_chk CHECK (status IN ('pending', 'completed', 'conflict', 'failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
